// Static geometry served by GET /api/layout (backend/world/layout.json). Not a message, so it
// lives outside /shared; only the fields the frontend draws are typed here.
export type XZ = [number, number];
export type MoverKind = "forklift" | "truck";

export interface LayoutNode {
  id: string;
  type: "rack_slot" | "zone" | "dock" | "bay" | "charger" | "junction" | "gate" | "exit" | "door" | "crossing" | "muster";
  x: number;
  z: number;
  kinds: MoverKind[];
  label?: string;
  spots?: XZ[];
}

export interface Rect { x: number; z: number; w: number; d: number }
export type Wall = "north" | "south" | "east" | "west";
export interface Opening { wall: Wall; at: number; w: number; label?: string }
export interface ProductionLine {
  conveyor: { from: XZ; to: XZ; width: number };
  machines: { id: string; label: string; x: number; z: number; w: number; d: number; h: number; kind: "press" | "packer"; line?: number }[];
  conveyor2?: { from: XZ; to: XZ; width: number };
  qc: { x: number; z: number; label: string };
  outbound_node: string;
}

export interface Layout {
  version: string;
  site: { id: string; name: string; short: string };
  bounds: { x: XZ; z: XZ };
  buildings: (Rect & { id: string; kind: "warehouse" | "office" | "factory" | "cold_room"; h: number; label?: string;
    doors?: { id: string; dock: string; wall: "south"; x: number; w: number }[];
    /** Open gaps in a wall: `at` is the x (north/south walls) or z (east/west walls) of the gap centre. */
    openings?: Opening[];
    door?: Opening & { wall: Wall } })[];
  production_line?: ProductionLine;
  racks: (Rect & { id: string; row: string; slots: string[] })[];
  zones: (Rect & { id: string; name: string; purpose: string })[];
  roads: { id: string; points: XZ[]; width: number; dashed: boolean }[];
  parking: (Rect & { id: string })[];
  fence: { lines: XZ[][]; gate: { x: number; z0: number; z1: number } };
  decor: { trees: XZ[]; containers: { x: number; z: number; heading_rad: number; color: string }[] };
  nodes: LayoutNode[];
  lanes: { a: string; b: string; kinds: MoverKind[]; reverse_into?: string | null }[];
  docks: { id: string; node: string; bay_node: string; door: string; label: string }[];
  chargers: { id: string; node: string; label: string }[];
  gate_node: string;
  exit_node: string;
  gateway: { id: string; label: string; x: number; z: number; ble_range_m: number };
  campus?: Campus;
}

/** Riverside Campus (layout.json `campus`, generated by tools/campus/gen_campus.py). */
export interface CampusBuilding {
  id: string; kind: string; name: string; x: number; z: number; w: number; d: number; h: number; zone: string; door: string;
  doors?: { id: string; wall: Wall; at: number; w: number; node: string }[];
}
export interface Campus {
  name: string;
  buildings: CampusBuilding[];
  tanks: { id: string; x: number; z: number; r: number; h: number; label: string; zone: string }[];
  etp: { id: string; x: number; z: number; w: number; d: number; zone: string; door: string; basins: { x: number; z: number; w: number; d: number; label: string }[] };
  weighbridge: { id: string; x: number; z: number; w: number; d: number; node: string; label: string };
  barrier: { id: string; x: number; z0: number; z1: number; node: string; label: string };
  parking: {
    cars: Rect & { rows: number; bays_per_row: number; label: string };
    two_wheelers: Rect & { label: string };
    ev_chargers: { id: string; x: number; z: number; w: number; d: number }[];
  };
  muster_points: { id: string; name: string; x: number; z: number; radius_m: number; node: string }[];
  solar: { id: string; building: string; kwp: number; panels: [number, number, number, number][] }[];
  hydrants: { ring: XZ[]; points: XZ[] };
  crossings: { id: string; a: string; b: string; over: "road" | "forklift"; x: number; z: number; hotspot: { x: number; z: number; radius_m: number } }[];
  walkways: { id: string; points: XZ[]; width: number }[];
  green_belt: Rect[];
  fence: { lines: (XZ | [])[][] };
}

export async function fetchLayout(): Promise<Layout> {
  const r = await fetch("/api/layout");
  if (!r.ok) throw new Error(`GET /api/layout: ${r.status}`);
  return (await r.json()) as Layout;
}
